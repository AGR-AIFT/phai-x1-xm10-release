#!/usr/bin/env python3
"""
version_generator.py — Git Tag → version.h Auto Generator

Location: Extension_Module/tools/ (App FW build pipeline)

Reads the latest git tag (format: vMAJOR.MINOR.PATCH.DEBUG) and writes
Core/Inc/version.h with FW_VER_MAJOR/MINOR/PATCH/DEBUG defines.

Usage:
    python tools/version_generator.py              # From Extension_Module/ root
    python version_generator.py                    # From Extension_Module/tools/
    python version_generator.py --validate         # Parse-only, no file write

Git tag format:  v<MAJOR>.<MINOR>.<PATCH>.<DEBUG>
    e.g., v1.2.3.0, v2.0.0.1

Each field must be 0-255 (uint8_t) to fit AGR_FwInfo_t header.

Can be called from STM32CubeIDE Post-Build Step:
    python "${ProjDirPath}/tools/version_generator.py"

Copyright (c) Angel Robotics Inc.
"""
from __future__ import annotations

import argparse
import os
import re
import subprocess
import sys


def get_git_version() -> str:
    """Get version from `git describe --tags`."""
    try:
        version = subprocess.check_output(
            ["git", "describe", "--tags", "--abbrev=0"],
            stderr=subprocess.STDOUT
        ).strip().decode('utf-8')
    except subprocess.CalledProcessError as e:
        print(f"WARNING: git describe failed: {e.output.decode('utf-8').strip()}")
        print("  Using default version v1.0.0.0 (no tag found)")
        version = "v1.0.0.0"
    except FileNotFoundError:
        print("WARNING: git not found in PATH")
        print("  Using default version v1.0.0.0")
        version = "v1.0.0.0"
    return version


def parse_version(version: str) -> tuple[int, int, int, int]:
    """Parse 'vMAJOR.MINOR.PATCH[.DEBUG]' -> (major, minor, patch, debug)."""
    match = re.match(r"v?(\d+)\.(\d+)\.(\d+)(?:\.(\d+))?", version)
    if not match:
        print(f"WARNING: Cannot parse version '{version}', using 0.0.0.0")
        return (0, 0, 0, 0)

    major = int(match.group(1))
    minor = int(match.group(2))
    patch = int(match.group(3))
    debug = int(match.group(4)) if match.group(4) else 0

    for name, val in [("major", major), ("minor", minor),
                      ("patch", patch), ("debug", debug)]:
        if not (0 <= val <= 255):
            print(f"ERROR: {name}={val} out of range (0-255)", file=sys.stderr)
            sys.exit(1)

    return (major, minor, patch, debug)


def write_version_h(output_file: str, major: int, minor: int,
                    patch: int, debug: int) -> None:
    """Write version.h with include guard and Doxygen header."""
    content = f"""\
/**
 * @file  version.h
 * @author Angel Robotics
 * @brief  Application firmware version definition
 * @details
 *   Auto-generated by version_generator.py from git tag (vMAJOR.MINOR.PATCH.DEBUG).
 *   Manual editing is allowed but version_generator.py will overwrite on next run.
 *   Each field must be 0-255 (uint8_t) to fit AGR_FwInfo_t and packaged.bin header.
 * @copyright Copyright (c) Angel Robotics Inc.
 */

#ifndef XM_FW_SYSTEM_CONFIG_VERSION_H_
#define XM_FW_SYSTEM_CONFIG_VERSION_H_

#define FW_VER_MAJOR    {major}
#define FW_VER_MINOR    {minor}
#define FW_VER_PATCH    {patch}
#define FW_VER_DEBUG    {debug}

#endif /* XM_FW_SYSTEM_CONFIG_VERSION_H_ */
"""
    os.makedirs(os.path.dirname(output_file), exist_ok=True)
    with open(output_file, "w", newline="\n") as f:
        f.write(content)


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Git Tag -> version.h auto generator (Angel Robotics)")
    parser.add_argument('--validate', action='store_true',
                        help="Parse git tag and print version, no file write")
    args = parser.parse_args()

    version = get_git_version()
    major, minor, patch, debug = parse_version(version)

    print(f"Git tag: {version} -> v{major}.{minor}.{patch}.{debug}")

    if args.validate:
        print("Validate mode -- no file written.")
        return

    # tools/build/ is two levels below Extension_Module/
    script_dir = os.path.dirname(os.path.abspath(__file__))
    project_root = os.path.dirname(os.path.dirname(script_dir))  # Extension_Module/
    output_file = os.path.join(project_root, "XM_FW", "System", "Config", "version.h")

    write_version_h(output_file, major, minor, patch, debug)
    print(f"Written: {output_file}")


if __name__ == "__main__":
    main()
